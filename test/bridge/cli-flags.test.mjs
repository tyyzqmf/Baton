import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import { USAGE, cliInfoOutput } from '../../bridge/cli.mjs';
import { BRIDGE_VERSION } from '../../bridge/version.mjs';

const BRIDGE_DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', '..', 'bridge');
const BRIDGE = path.join(BRIDGE_DIR, 'bridge.mjs');

function tempHome() {
  return fs.mkdtempSync(path.join(os.tmpdir(), 'baton-cli-'));
}

function runBridge(home, args, { timeout = 20_000 } = {}) {
  return spawnSync(process.execPath, [BRIDGE, ...args], {
    env: { ...process.env, HOME: home, USERPROFILE: home },
    encoding: 'utf-8',
    timeout,
  });
}

function listTree(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { recursive: true }).sort();
}

async function withRecordingServer(fn) {
  const requests = [];
  const server = http.createServer((req, res) => { requests.push(req.url); res.end('{}'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  try {
    return await fn(`http://127.0.0.1:${server.address().port}/v1`, requests);
  } finally {
    await new Promise(resolve => server.close(resolve));
  }
}

function writeConfig(home, server) {
  const file = path.join(home, '.baton-bridge', 'config.json');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  // No bridgeId on purpose: a normal start would generate and save one.
  const body = JSON.stringify({ server, apiKey: 'test-key-not-real', deviceName: 'box', deviceDisplayName: 'box' }, null, 2);
  fs.writeFileSync(file, body, { mode: 0o600 });
  return { file, body };
}

test('SPEC-0001/AC-1: --version prints one line with the reported Bridge version and exits 0', () => {
  assert.equal(cliInfoOutput(['--version']), `${BRIDGE_VERSION}\n`);
  const home = tempHome();
  const result = runBridge(home, ['--version']);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, `${BRIDGE_VERSION}\n`);
  assert.equal(result.stdout.trim(), 'dev');
  fs.rmSync(home, { recursive: true, force: true });
});

test('SPEC-0001/AC-1: a published package prints the version install.sh wrote', () => {
  const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'baton-cli-stage-'));
  for (const name of ['cli.mjs', 'cli-guard.mjs']) fs.copyFileSync(path.join(BRIDGE_DIR, name), path.join(stage, name));
  fs.writeFileSync(path.join(stage, 'version.mjs'), "// Generated by server/install.sh\nexport const BRIDGE_VERSION = '1.1.0';\n");
  const result = spawnSync(process.execPath, [path.join(stage, 'cli-guard.mjs'), '--version'], { encoding: 'utf-8' });
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, '1.1.0\n');
  fs.rmSync(stage, { recursive: true, force: true });
});

test('SPEC-0001/AC-2: --version without a config creates nothing and exits 0', () => {
  const home = tempHome();
  const result = runBridge(home, ['--version']);
  assert.equal(result.status, 0, result.stderr);
  assert.deepEqual(listTree(home), []);
  fs.rmSync(home, { recursive: true, force: true });
});

test('SPEC-0001/AC-2, SPEC-0001/AC-3: --version and --help with a config do not connect, write config or start syncing', async () => {
  await withRecordingServer(async (server, requests) => {
    for (const flag of ['--version', '--help']) {
      const home = tempHome();
      const { file, body } = writeConfig(home, server);
      const before = listTree(home);
      const result = runBridge(home, [flag]);
      assert.equal(result.status, 0, result.stderr);
      assert.equal(fs.readFileSync(file, 'utf-8'), body);
      assert.deepEqual(listTree(home), before);
      assert.doesNotMatch(result.stdout, /Baton Bridge started|\[sync\]|\[ws\]/);
      fs.rmSync(home, { recursive: true, force: true });
    }
    assert.deepEqual(requests, []);
  });
});

test('SPEC-0001/AC-3: --help lists all six options and exits 0', () => {
  for (const option of ['--server', '--key', '--name', '--skip-init', '--version', '--help']) {
    const lines = USAGE.split('\n').filter(line => line.trimStart().startsWith(`${option} `));
    assert.equal(lines.length, 1, option);
  }
  const home = tempHome();
  const result = runBridge(home, ['--help']);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, USAGE);
  assert.deepEqual(listTree(home), []);
  fs.rmSync(home, { recursive: true, force: true });
});

test('SPEC-0001/AC-4: --help wins over --version', () => {
  assert.equal(cliInfoOutput(['--version', '--help']), USAGE);
  assert.equal(cliInfoOutput(['--help', '--version']), USAGE);
  const home = tempHome();
  const result = runBridge(home, ['--version', '--help']);
  assert.equal(result.status, 0, result.stderr);
  assert.equal(result.stdout, USAGE);
  assert.ok(!result.stdout.split('\n').includes(BRIDGE_VERSION));
  fs.rmSync(home, { recursive: true, force: true });
});

test('SPEC-0001/AC-5: other arguments are ignored and the config is not rewritten', async () => {
  await withRecordingServer(async (server, requests) => {
    for (const flag of ['--version', '--help']) {
      const home = tempHome();
      const { file, body } = writeConfig(home, server);
      const args = ['--server', `${server}/other`, '--key', 'other-key-not-real', '--name', 'renamed', '--skip-init', flag];
      const result = runBridge(home, args);
      assert.equal(result.status, 0, result.stderr);
      assert.equal(result.stdout, flag === '--help' ? USAGE : `${BRIDGE_VERSION}\n`);
      assert.equal(fs.readFileSync(file, 'utf-8'), body);
      assert.doesNotMatch(result.stdout, /other-key-not-real|test-key-not-real|127\.0\.0\.1|renamed|box/);
      fs.rmSync(home, { recursive: true, force: true });
    }
    assert.deepEqual(requests, []);
  });
});

test('SPEC-0001/AC-6: without --version/--help the Bridge starts as before', () => {
  for (const args of [[], ['--skip-init'], ['--server', 'https://baton.test/v1', '--key', 'k', '--name', 'box'], ['--unknown']]) {
    assert.equal(cliInfoOutput(args), null);
  }
  const source = fs.readFileSync(BRIDGE, 'utf-8');
  const firstImport = source.split('\n').find(line => line.startsWith('import '));
  assert.equal(firstImport, "import './cli-guard.mjs';");

  const home = tempHome();
  const result = runBridge(home, ['--unknown']);
  assert.equal(result.status, 1);
  assert.equal(result.stdout, '');
  assert.match(result.stderr, /^Usage: node bridge\.mjs --server URL --key API_KEY \[--name DEVICE_NAME\]$/m);
  assert.equal(fs.existsSync(path.join(home, '.baton-bridge', 'config.json')), false);
  fs.rmSync(home, { recursive: true, force: true });
});
