import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import http from 'node:http';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { fileURLToPath } from 'node:url';

import { USAGE, cliInfoOutput } from '../../bridge/cli.mjs';

const BRIDGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../bridge');
const FLAGS = ['--server', '--key', '--name', '--skip-init', '--version', '--help'];

function tempHome(t) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'baton-cli-'));
  t.after(() => fs.rmSync(home, { recursive: true, force: true }));
  return home;
}

function runBridge(args, home, entry = path.join(BRIDGE_DIR, 'bridge.mjs')) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [entry, ...args], {
      env: { ...process.env, HOME: home, USERPROFILE: home },
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    let stdout = '';
    let stderr = '';
    child.stdout.on('data', chunk => { stdout += chunk; });
    child.stderr.on('data', chunk => { stderr += chunk; });
    const timer = setTimeout(() => { child.kill(); reject(new Error(`bridge did not exit: ${stderr}`)); }, 30_000);
    child.once('error', reject);
    child.once('close', code => { clearTimeout(timer); resolve({ code, stdout, stderr }); });
  });
}

async function countingServer(t) {
  const requests = [];
  const server = http.createServer((req, res) => { requests.push(req.url); res.end('{}'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => server.close());
  return { url: `http://127.0.0.1:${server.address().port}`, requests };
}

function snapshot(dir) {
  if (!fs.existsSync(dir)) return null;
  return Object.fromEntries(fs.readdirSync(dir).sort().map(name => [name, fs.readFileSync(path.join(dir, name), 'utf-8')]));
}

test('--version prints only the version line', () => {
  // SPEC-0001/AC-1
  assert.equal(cliInfoOutput(['--version'], 'dev'), 'dev\n');
  assert.equal(cliInfoOutput(['--version'], '1.1.0'), '1.1.0\n');
});

test('--help documents each of the six flags on its own line', () => {
  // SPEC-0001/AC-3
  assert.equal(cliInfoOutput(['--help'], 'dev'), USAGE);
  for (const flag of FLAGS) {
    assert.equal(USAGE.split('\n').filter(line => line.trimStart().startsWith(`${flag} `)).length, 1, flag);
  }
});

test('--help wins over --version', () => {
  // SPEC-0001/AC-4
  assert.equal(cliInfoOutput(['--version', '--help'], '1.1.0'), USAGE);
  assert.equal(cliInfoOutput(['--help', '--version'], '1.1.0'), USAGE);
  assert.ok(!USAGE.includes('1.1.0'));
});

test('other arguments do not change the informational output', () => {
  // SPEC-0001/AC-5
  const others = ['--server', 'https://baton.test/v1', '--key', 'secret-key', '--name', 'box', '--skip-init', '--unknown'];
  assert.equal(cliInfoOutput([...others, '--version'], 'dev'), 'dev\n');
  assert.equal(cliInfoOutput(['--help', ...others], 'dev'), USAGE);
});

test('ordinary and service starts are not informational', () => {
  // SPEC-0001/AC-6
  for (const args of [[], ['--skip-init'], ['--server', 'https://baton.test/v1', '--key', 'k', '--name', 'n'], ['--unknown']]) {
    assert.equal(cliInfoOutput(args, 'dev'), null);
  }
});

test('source Bridge prints dev and exits 0 without creating any config', async t => {
  // SPEC-0001/AC-1 SPEC-0001/AC-2
  const home = tempHome(t);
  const result = await runBridge(['--version'], home);
  assert.equal(result.code, 0);
  assert.equal(result.stdout, 'dev\n');
  assert.equal(fs.existsSync(path.join(home, '.baton-bridge')), false);
});

test('a published Bridge prints the version install.sh wrote', async t => {
  // SPEC-0001/AC-1
  const home = tempHome(t);
  const stage = fs.mkdtempSync(path.join(os.tmpdir(), 'baton-cli-stage-'));
  t.after(() => fs.rmSync(stage, { recursive: true, force: true }));
  for (const name of fs.readdirSync(BRIDGE_DIR).filter(name => name.endsWith('.mjs'))) {
    fs.copyFileSync(path.join(BRIDGE_DIR, name), path.join(stage, name));
  }
  fs.cpSync(path.join(BRIDGE_DIR, 'project'), path.join(stage, 'project'), { recursive: true });
  fs.symlinkSync(path.join(BRIDGE_DIR, 'node_modules'), path.join(stage, 'node_modules'), 'junction');
  fs.writeFileSync(path.join(stage, 'version.mjs'), "// Generated by server/install.sh\nexport const BRIDGE_VERSION = '1.1.0';\n");
  const result = await runBridge(['--version'], home, path.join(stage, 'bridge.mjs'));
  assert.equal(result.code, 0);
  assert.equal(result.stdout, '1.1.0\n');
});

test('with an existing config, --version and --help neither connect nor rewrite it', async t => {
  // SPEC-0001/AC-2 SPEC-0001/AC-3 SPEC-0001/AC-4 SPEC-0001/AC-5
  const server = await countingServer(t);
  const home = tempHome(t);
  const bridgeHome = path.join(home, '.baton-bridge');
  fs.mkdirSync(bridgeHome);
  // No deviceDisplayName and no bridgeId: a normal start would add both and save.
  fs.writeFileSync(path.join(bridgeHome, 'config.json'), JSON.stringify({ server: server.url, apiKey: 'old-key', deviceName: 'box' }));
  const before = snapshot(bridgeHome);
  const other = await countingServer(t);

  for (const args of [
    ['--version'],
    ['--help'],
    ['--version', '--help'],
    ['--server', other.url, '--key', 'new-key', '--name', 'renamed', '--version'],
    ['--help', '--server', other.url, '--key', 'new-key', '--skip-init'],
  ]) {
    const result = await runBridge(args, home);
    assert.equal(result.code, 0, args.join(' '));
    assert.equal(result.stdout, args.includes('--help') ? USAGE : 'dev\n', args.join(' '));
    for (const secret of ['old-key', 'new-key', server.url, other.url, 'box', 'renamed']) {
      assert.ok(!result.stdout.includes(secret), `${args.join(' ')} leaked ${secret}`);
    }
    assert.deepEqual(snapshot(bridgeHome), before, args.join(' '));
  }
  assert.deepEqual(server.requests, []);
  assert.deepEqual(other.requests, []);
});

test('without the new flags the Bridge still asks for a config and exits 1', async t => {
  // SPEC-0001/AC-6
  const home = tempHome(t);
  const result = await runBridge([], home);
  assert.equal(result.code, 1);
  assert.equal(result.stdout, '');
  assert.match(result.stderr, /^Usage: node bridge\.mjs --server URL --key API_KEY \[--name DEVICE_NAME\]$/m);
});
